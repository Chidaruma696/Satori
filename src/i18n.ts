const tables: Record<string, Table> = { es, de, fr, it, pt, ja, ru };

/** The first of the browser's preferred languages that we have; English otherwise. */
function pick(): string {
  const wanted = navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const l of wanted) {
    const base = l.toLowerCase().split('-')[0];
    if (base === 'en') return 'en';
    if (base in tables) return base;
  }
  return 'en';
}

export const lang = pick();
document.documentElement.lang = lang;
const table: Table | undefined = tables[lang];

/** Translate a UI string; unknown strings come back unchanged. */
export function t(s: string): string {
  return (table as Record<string, string> | undefined)?.[s] ?? s;
}
